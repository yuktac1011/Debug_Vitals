def _format_payload_comment(payload: Dict[str, Any]) -> str:
    """Format a payload dict as a Python comment block."""
    import json
    try:
        lines = json.dumps(payload, indent=2, default=str).splitlines()
        return "\n        #   ".join(lines[:10])  # cap at 10 lines
    except Exception:
        return str(payload)[:200]


def _suggest_test_path(event_type: str, payload: Dict[str, Any], extension: str) -> str:
    """Suggest a file path for the generated test."""
    target = payload.get("target") or payload.get("path") or ""
    if target:
        # Place test alongside the source file
        import os
        base = os.path.basename(target)
        name_no_ext = os.path.splitext(base)[0]
        return f"tests/regression/test_{name_no_ext}{extension}"
    return f"tests/regression/test_{event_type}_regression{extension}"


