"""
Test generator — generates regression tests from a diagnosis.

Generates test code that would have caught the diagnosed root cause.
Uses a template-based approach for deterministic generation, with
an optional LLM enhancement path that falls back gracefully.

Generated tests are framework-aware (pytest, jest, etc.) based on the
language detected in the session's environment snapshot events.
"""

import logging
import uuid
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

# Supported test frameworks and their file extensions
_FRAMEWORK_MAP = {
    "python": ("pytest", ".py"),
    "node": ("jest", ".test.js"),
    "javascript": ("jest", ".test.js"),
    "typescript": ("jest", ".test.ts"),
    "go": ("go_test", "_test.go"),
    "rust": ("cargo_test", "_test.rs"),
}

_DEFAULT_FRAMEWORK = ("pytest", ".py")


def generate_regression_test(
    root_cause: Dict[str, Any],
    diagnosis_id: str,
    session_id: str,
    language: Optional[str] = None,
    target_file: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Generate a regression test for a given root cause.

    Parameters
    ----------
    root_cause:
        A root cause dict from the ranker (event_id, score, reason, event_type, payload).
    diagnosis_id:
        ID of the parent diagnosis.
    session_id:
        ID of the parent session.
    language:
        Detected language from env_snapshot (e.g. "python", "node").
    target_file:
        File path where the test should be placed.

    Returns
    -------
    dict with keys:
        test_code, test_framework, target_file_path, metadata
    """
    event_type = root_cause.get("event_type", "unknown")
    payload = root_cause.get("payload", {})
    reason = root_cause.get("reason", "")
    rank = root_cause.get("rank", 1)

    framework, extension = _FRAMEWORK_MAP.get(
        (language or "python").lower(), _DEFAULT_FRAMEWORK
    )

    test_code = _render_test(
        framework=framework,
        event_type=event_type,
        payload=payload,
        reason=reason,
        rank=rank,
        diagnosis_id=diagnosis_id,
    )

    suggested_path = (
        target_file
        or _suggest_test_path(event_type, payload, extension)
    )

    return {
        "test_code": test_code,
        "test_framework": framework,
        "target_file_path": suggested_path,
        "metadata": {
            "source_event_type": event_type,
            "source_event_id": root_cause.get("event_id"),
            "root_cause_rank": rank,
            "root_cause_score": root_cause.get("score"),
            "diagnosis_id": diagnosis_id,
            "session_id": session_id,
        },
    }


# ── Template renderers ─────────────────────────────────────────────────────────

def _render_test(
    framework: str,
    event_type: str,
    payload: Dict[str, Any],
    reason: str,
    rank: int,
    diagnosis_id: str,
) -> str:
    """Select and render the appropriate test template."""
    renderer = _TEST_RENDERERS.get(framework, _render_pytest_generic)
    return renderer(event_type, payload, reason, rank, diagnosis_id)


